const qs=(s,ctx=document)=>ctx.querySelector(s);
const qsa=(s,ctx=document)=>[...ctx.querySelectorAll(s)];

let lang = localStorage.getItem("bgq-lang") || "en";
function applyLang(next){
  lang = next;
  document.documentElement.lang = next;
  localStorage.setItem("bgq-lang", next);
  qsa("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(translations[next][key] !== undefined) el.textContent=translations[next][key];
  });
  qsa("[data-i18n-placeholder]").forEach(el=>{
    const key=el.dataset.i18nPlaceholder;
    if(translations[next][key] !== undefined) el.placeholder=translations[next][key];
  });
  qsa(".lang-btn").forEach(b=>b.classList.toggle("active",b.dataset.lang===next));
}
qsa(".lang-btn").forEach(b=>b.addEventListener("click",()=>applyLang(b.dataset.lang)));
applyLang(lang);

const navToggle=qs(".nav-toggle"), nav=qs(".main-nav");
navToggle.addEventListener("click",()=>{
  const open=nav.classList.toggle("open");
  navToggle.setAttribute("aria-expanded",String(open));
});
qsa(".main-nav a").forEach(a=>a.addEventListener("click",()=>{
  nav.classList.remove("open");navToggle.setAttribute("aria-expanded","false");
}));

const observer=new IntersectionObserver(entries=>{
  entries.forEach(e=>{ if(e.isIntersecting){e.target.classList.add("is-visible");observer.unobserve(e.target);} });
},{threshold:.12});
qsa(".reveal").forEach(el=>observer.observe(el));

const progress=qs(".page-progress span");
addEventListener("scroll",()=>{
  const h=document.documentElement.scrollHeight-innerHeight;
  progress.style.width = (h>0 ? (scrollY/h)*100 : 0) + "%";
},{passive:true});

qs("#year").textContent=new Date().getFullYear();

const lightbox=qs("#lightbox"), lightContent=qs(".lightbox-content");
qsa(".shot").forEach(shot=>{
  shot.addEventListener("click",()=>{
    const clone=shot.firstElementChild.cloneNode(true);
    lightContent.replaceChildren(clone);
    lightbox.showModal();
  });
});
qs(".lightbox-close").addEventListener("click",()=>lightbox.close());
lightbox.addEventListener("click",(e)=>{
  const r=lightbox.getBoundingClientRect();
  if(e.clientX<r.left||e.clientX>r.right||e.clientY<r.top||e.clientY>r.bottom) lightbox.close();
});

const form=qs("#contactForm"), status=qs(".form-status");
form.addEventListener("submit",(e)=>{
  e.preventDefault();
  if(!form.checkValidity()){
    status.textContent=translations[lang].formError;
    form.reportValidity();
    return;
  }
  status.textContent=translations[lang].formDemo;
  form.reset();
});
